"""Every number in docs/results.md, from the tables in data/ (Python 3 standard library only).

  python3 scripts/results.py [--data data] [--out docs/results.md]
"""
import argparse, collections, csv, os

ap = argparse.ArgumentParser()
ap.add_argument("--data", default="data")
ap.add_argument("--out", default=os.path.join("docs", "results.md"))
a = ap.parse_args()
read = lambda n: list(csv.DictReader(open(os.path.join(a.data, n))))
sess, cells = read("sessions.csv"), read("cells.csv")
usable = [s for s in sess if s["status"] == "usable"]
C = collections.Counter
f = lambda x: float(x) if x not in ("", None) else 0.0

L = ["# Results", "", "Generated by `scripts/results.py` from `data/`. Definitions: `../README.md`.", "",
     "## Sessions", "", "| Status | Sessions |", "|---|---|"]
st = C(s["status"] for s in sess)
for k in ("usable", "not_usable"):
    L.append(f"| {k} | {st[k]} |")
nu = C(s["status_reason"].split(":")[0] for s in sess if s["status"] == "not_usable")
L += ["", "Not usable, by reason: " + ", ".join(f"{k} {v}" for k, v in sorted(nu.items())) + " (`selection.md`).",
      "", f"Usable: {len(usable)} sessions from {len({s['repo_id'] for s in usable})} repositories."]

L += ["", "## Outcome categories (usable sessions)", "", "| Category | Sessions | Original completed: yes | partial |", "|---|---|---|---|"]
for k in ("baseline passes, no other cell passes", "baseline passes, another cell passes",
          "baseline fails, another cell passes", "all fail, original in grid", "all fail, original not in grid"):
    g = [s for s in usable if s["outcome_category"] == k]
    L.append(f"| {k} | {len(g)} | {sum(s['original_completed'] == 'yes' for s in g)} | {sum(s['original_completed'] == 'partial' for s in g)} |")

L += ["", "## Baselines that are not the hand-picked model and effort (usable sessions)", "", "| Reason | Sessions |", "|---|---|"]
for k, n in sorted(C(s["proxy_reason"] for s in usable if s["baseline_is_proxy"] == "True").items()):
    L.append(f"| {k} | {n} |")

L += ["", "## Pass rate per cell (usable sessions)", "", "| Cell (tier × effort) | Pass | Labelled | Rate |", "|---|---|---|---|"]
by = collections.defaultdict(lambda: [0, 0])
for r in cells:
    if r["verdict"] in ("pass", "fail"):
        k = f"{r['tier']}__{r['effort']}"; by[k][0] += r["verdict"] == "pass"; by[k][1] += 1
for k in ("haiku__none", "sonnet__low", "sonnet__medium", "sonnet__high", "opus__low", "opus__medium", "opus__high"):
    p, n = by[k]
    L.append(f"| {k} | {p} | {n} | {100 * p / n:.0f}% |" if n else f"| {k} | 0 | 0 | |")

L += ["", "## Cheapest passing cell (usable sessions)", "", "| Cell | Sessions |", "|---|---|"]
for k, n in sorted(C(s["cheapest_passing_cell"] or "none" for s in usable).items(), key=lambda x: (-x[1], x[0])):
    L.append(f"| {k} | {n} |")

L += ["", "## Oracle ceiling (usable sessions)", "", "| Sessions | n | Baseline cost | Cheapest passing cost | Saving |", "|---|---|---|---|---|"]
for name, sel in (("baseline passed", lambda s: s["baseline_verdict"] == "pass" and s["cheapest_passing_cell"]),
                  ("any cell passed", lambda s: s["cheapest_passing_cell"])):
    g = [s for s in usable if sel(s)]
    b = sum(f(s["baseline_cost_usd"]) for s in g); o = sum(f(s["cheapest_passing_cost_usd"]) for s in g)
    L.append(f"| {name} | {len(g)} | ${b:.2f} | ${o:.2f} | {100 * (1 - o / b):.1f}% |" if b else f"| {name} | 0 | | | |")

g = [s for s in usable if s["original_completed"] == "yes"]
L += ["", "## Replay faithfulness", "",
      f"The baseline cell passes in {sum(s['baseline_verdict'] == 'pass' for s in g)} of the {len(g)} usable sessions whose original completed."]

lab = [r for r in cells if r["verdict"] in ("pass", "fail")]
ov = [r for r in lab if r["verdict_source"] == "override"]
L += ["", "## Labels", "",
      f"{len(lab)} labelled cells; {sum(int(r['votes']) > 1 for r in lab)} decided by a majority of 3 (first verdict below "
      f"confidence 0.7); {sum(r['flag_for_review'] == 'True' for r in lab)} flagged for review. Human overrides: {len(ov)} "
      f"({', '.join(f'{a_}→{b_} {n}' for (a_, b_), n in sorted(C((r['judge_verdict'], r['verdict']) for r in ov).items()))})."]

tot = lambda k: sum(f(r[k]) for r in cells)
L += ["", "## Cost of the shipped replays", "",
      f"Replays ${tot('cost_usd'):.2f} (label cost ${tot('cost_usd_label'):.2f}), emulated user ${tot('emulated_user_cost_usd'):.2f}, "
      f"judge ${tot('judge_cost_usd'):.2f} (final labels only), at Amazon Bedrock list prices."]
os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
open(a.out, "w").write("\n".join(L) + "\n")
print(f"wrote {a.out}")
